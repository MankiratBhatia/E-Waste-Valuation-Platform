# ─── Helpers ──────────────────────────────────────────────────────────────────

def _safe(text: str) -> str:
    replacements = {
        "\u2014": "-", "\u2013": "-", "\u2019": "'", "\u2018": "'",
        "\u201c": '"', "\u201d": '"', "\u20b9": "INR", "\u2192": "->",
        "\u2022": "*", "&": "and",
    }
    for k, v in replacements.items():
        text = text.replace(k, v)
    return text.encode("latin-1", errors="replace").decode("latin-1")


def _fmt_inr(amount: float) -> str:
    return f"Rs. {amount:,.2f}"


def _fmt_date(dt) -> str:
    if not dt:
        return datetime.utcnow().strftime("%d %B %Y")
    return dt.strftime("%d %B %Y")


# ─── PDF Class ────────────────────────────────────────────────────────────────

class CertPDF(FPDF):
    def header(self):
        pass  # custom header per page

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(120, 120, 120)
        self.set_draw_color(180, 180, 180)
        self.line(15, self.get_y(), 195, self.get_y())
        self.ln(2)
        self.set_x(15)
        self.cell(0, 5,
            f"System-generated by Terionix-MRIS  |  E-Waste (Management) Rules 2022, MoEFCC, Govt. of India  |  Page {self.page_no()}",
            align="C")

    def page_header_block(self, subtitle: str):
        """Top letterhead for each page."""
        # Logo area — left side
        self.set_xy(15, 18)
        self.set_font("Helvetica", "B", 20)
        self.set_text_color(20, 20, 20)
        self.cell(80, 10, "TERIONIX", ln=False)

        # Right side — registration info
        self.set_font("Helvetica", "", 7.5)
        self.set_text_color(80, 80, 80)
        self.set_xy(110, 18)
        self.cell(85, 5, "Terionix Material Recovery Pvt. Ltd.", ln=True, align="R")
        self.set_x(110)
        self.cell(85, 4, "EPR Reg. No.: CPCB/EPR/TRX/2024/0047", ln=True, align="R")
        self.set_x(110)
        self.cell(85, 4, "GSTIN: 27AAACT1234F1ZK", ln=True, align="R")
        self.set_x(110)
        self.cell(85, 4, "support@terionix.in  |  +91-80-4567-8901", ln=True, align="R")

        # Tagline under logo
        self.set_xy(15, 28)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(100, 100, 100)
        self.cell(80, 5, "Material Recovery Intelligence System")

        # Horizontal rule
        self.set_draw_color(40, 40, 40)
        self.set_line_width(0.6)
        self.line(15, 37, 195, 37)
        self.set_line_width(0.2)
        self.ln(0)
        self.set_y(38)

        # Document title
        self.set_font("Helvetica", "B", 13)
        self.set_text_color(20, 20, 20)
        self.set_x(15)
        self.cell(0, 9, _safe(subtitle), align="C", ln=True)

        # Light rule under title
        self.set_draw_color(160, 160, 160)
        self.line(15, self.get_y(), 195, self.get_y())
        self.ln(5)

    def section_title(self, title: str):
        self.set_font("Helvetica", "B", 8.5)
        self.set_text_color(30, 30, 30)
        self.set_x(15)
        # Underline via draw
        y = self.get_y()
        self.cell(0, 6, _safe(title.upper()), ln=True)
        self.set_draw_color(180, 180, 180)
        self.line(15, self.get_y(), 195, self.get_y())
        self.ln(2)

    def kv(self, key: str, value: str, key_w: int = 72):
        self.set_x(18)
        self.set_font("Helvetica", "", 9)
        self.set_text_color(90, 90, 90)
        self.cell(key_w, 6, _safe(key) + ":")
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(20, 20, 20)
        self.cell(0, 6, _safe(str(value)), ln=True)

    def spacer(self, h: int = 4):
        self.ln(h)


