    pdf.set_fill_color(245, 245, 245)
    pdf.set_draw_color(200, 200, 200)
    pdf.set_x(15)
    pdf.set_font("Helvetica", "", 8.5)
    pdf.set_text_color(50, 50, 50)
    bar_y = pdf.get_y()
    pdf.cell(60, 7, f"  Certificate No: {cert_num}", fill=True, border=1)
    pdf.cell(60, 7, f"  Issue Date: {issue_date}", fill=True, border=1)
    pdf.cell(60, 7, f"  Batch Ref: {batch.batch_id[:12].upper()}...", fill=True, border=1)
    pdf.ln(9)

    # ── Section 1 ─────────────────────────────────────────────────────────────
    pdf.spacer(3)
    pdf.section_title("1.  Certificate and Recycler Details")
    pdf.kv("Certificate Number",    cert_num)
    pdf.kv("Date of Issue",         issue_date)
    pdf.kv("Batch Reference ID",    batch.batch_id.upper())
    pdf.kv("Authorized Recycler",   "Terionix Material Recovery Pvt. Ltd.")
    pdf.kv("EPR Registration No.",  "CPCB/EPR/TRX/2024/0047")
    pdf.kv("Recycler Category",     "Authorized Dismantler and Recycler (Category A)")
