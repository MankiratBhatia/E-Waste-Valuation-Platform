    pdf.kv("Company Name",          _safe(supplier.name))
    pdf.kv("Supplier ID",           supplier.supplier_id[:20].upper())
    pdf.kv("EPR Portal",            "MoEFCC EPR Portal (eprewaste.gov.in)")
    pdf.kv("Producer Category",     "IT Equipment / Consumer Electronics")
    pdf.spacer(5)

    # ── Section 3 ─────────────────────────────────────────────────────────────
    pdf.section_title("3.  E-Waste Description")
    pdf.kv("Device Category",       batch.device_type.replace("_", " ").title())
    pdf.kv("Condition at Intake",   batch.condition.title())
    pdf.kv("Gross Weight Collected",f"{batch.weight:.2f} kg")
    pdf.kv("Batch Segment",         batch.segment or "N/A")
    pdf.kv("Collection Date",       _fmt_date(batch.submitted_at))
    if batch.completed_at:
        pdf.kv("Recovery Completion", _fmt_date(batch.completed_at))
    pdf.spacer(5)

    # ── Section 4 ─────────────────────────────────────────────────────────────
    pdf.section_title("4.  Valuation Summary")
    pdf.kv("Expected Recovery Value (ERV)", _fmt_inr(batch.expected_value or 0))
    pdf.kv("Guaranteed Offer Price",        _fmt_inr(batch.offer_price or 0))
    if batch.actual_value:
        pdf.kv("Actual Recovery Value",     _fmt_inr(batch.actual_value))
        err = abs((batch.actual_value - (batch.expected_value or 1)) / (batch.expected_value or 1)) * 100
        pdf.kv("Prediction Accuracy",       f"{100 - err:.1f}%")
    pdf.kv("Currency",                      "Indian Rupees (INR)")
    pdf.spacer(5)

    # ── Section 5 — Declaration ───────────────────────────────────────────────
    pdf.section_title("5.  Compliance Declaration")
    pdf.set_x(18)
